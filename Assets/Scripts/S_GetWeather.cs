using System.Collections;
using UnityEngine;
using UnityEngine.Networking;
using UnityEngine.XR.Interaction.Toolkit;
using UnityEngine.XR.Interaction.Toolkit.Interactors;

public class S_GetWeather : MonoBehaviour
{
    // ?? API ????????????????????????????????????????????????????????????????
    private const string API_URL =
        "https://api.open-meteo.com/v1/forecast" +
        "?latitude=48.4196&longitude=-71.0637" +
        "&current=temperature_2m,relative_humidity_2m,apparent_temperature," +
        "is_day,showers,snowfall,precipitation,rain,weather_code," +
        "pressure_msl,surface_pressure,cloud_cover," +
        "wind_speed_10m,wind_direction_10m,wind_gusts_10m" +
        "&timezone=America%2FNew_York";

    // ?? Stored weather values ??????????????????????????????????????????????
    private string  fetchTime;
    private int     interval;
    private float   temperature;
    private int     relativeHumidity;
    private float   apparentTemperature;
    private int     isDay;
    private float   showers;
    private float   snowfall;
    private float   precipitation;
    private float   rain;
    private int     weatherCode;
    private float   pressureMsl;
    private float   surfacePressure;
    private int     cloudCover;
    private float   windSpeed;
    private int     windDirection;
    private float   windGusts;

    // ?? UI ?????????????????????????????????????????????????????????????????
    private TextMesh displayText;

    // ??????????????????????????????????????????????????????????????????????
    //  JSON data classes (JsonUtility-compatible)
    // ??????????????????????????????????????????????????????????????????????
    [System.Serializable]
    private class CurrentWeather
    {
        public string time;
        public int    interval;
        public float  temperature_2m;
        public int    relative_humidity_2m;
        public float  apparent_temperature;
        public int    is_day;
        public float  showers;
        public float  snowfall;
        public float  precipitation;
        public float  rain;
        public int    weather_code;
        public float  pressure_msl;
        public float  surface_pressure;
        public int    cloud_cover;
        public float  wind_speed_10m;
        public int    wind_direction_10m;
        public float  wind_gusts_10m;
    }

    [System.Serializable]
    private class WeatherResponse
    {
        public CurrentWeather current;
    }

    // ??????????????????????????????????????????????????????????????????????
    //  Unity lifecycle
    // ??????????????????????????????????????????????????????????????????????
    public void Start()
    {
        ChangeColor(Color.white);
        SetupDisplayText();
    }

    // ??????????????????????????????????????????????????????????????????????
    //  XR Interaction callbacks
    // ??????????????????????????????????????????????????????????????????????
    public void OnActivated(ActivateEventArgs args)
    {
        Debug.Log("Activated! Fetching weather…");
        ChangeColor(Color.yellow);
        StartCoroutine(FetchWeather());
    }

    public void OnDeactivated(DeactivateEventArgs args)
    {
        Debug.Log("Deactivated!");
        ChangeColor(Color.red);
    }

    public void OnSelectEntered(SelectEnterEventArgs args)
    {
        Debug.Log("Grabbed!");
        ChangeColor(Color.green);
    }

    public void OnSelectExited(SelectExitEventArgs args)
    {
        Debug.Log("Released!");
        ChangeColor(Color.black);
    }

    // ??????????????????????????????????????????????????????????????????????
    //  API fetch
    // ??????????????????????????????????????????????????????????????????????
    private IEnumerator FetchWeather()
    {
        UpdateDisplay("Fetching weather…");

        using (UnityWebRequest request = UnityWebRequest.Get(API_URL))
        {
            yield return request.SendWebRequest();

            if (request.result != UnityWebRequest.Result.Success)
            {
                string error = $"Weather fetch error: {request.error}";
                Debug.LogError(error);
                UpdateDisplay(error);
                yield break;
            }

            ParseAndStore(request.downloadHandler.text);
        }
    }

    private void ParseAndStore(string json)
    {
        WeatherResponse response = JsonUtility.FromJson<WeatherResponse>(json);

        if (response?.current == null)
        {
            Debug.LogError("Failed to parse weather JSON.");
            UpdateDisplay("Parse error.");
            return;
        }

        CurrentWeather c = response.current;

        // ?? Store to member variables ??????????????????????????????????
        fetchTime           = c.time;
        interval            = c.interval;
        temperature         = c.temperature_2m;
        relativeHumidity    = c.relative_humidity_2m;
        apparentTemperature = c.apparent_temperature;
        isDay               = c.is_day;
        showers             = c.showers;
        snowfall            = c.snowfall;
        precipitation       = c.precipitation;
        rain                = c.rain;
        weatherCode         = c.weather_code;
        pressureMsl         = c.pressure_msl;
        surfacePressure     = c.surface_pressure;
        cloudCover          = c.cloud_cover;
        windSpeed           = c.wind_speed_10m;
        windDirection       = c.wind_direction_10m;
        windGusts           = c.wind_gusts_10m;

        // ?? Log to console ?????????????????????????????????????????????
        Debug.Log(BuildWeatherString());

        // ?? Display on screen ??????????????????????????????????????????
        UpdateDisplay(BuildWeatherString());
    }

    // ??????????????????????????????????????????????????????????????????????
    //  Helpers
    // ??????????????????????????????????????????????????????????????????????
    private string BuildWeatherString()
    {
        return
            $"?? Current Weather ??\n" +
            $"Time         : {fetchTime}\n" +
            $"Interval     : {interval} s\n" +
            $"Condition    : {WmoDescription(weatherCode)} (WMO {weatherCode})\n" +
            $"Temperature  : {temperature} °C  (feels {apparentTemperature} °C)\n" +
            $"Humidity     : {relativeHumidity} %\n" +
            $"Precipitation: {precipitation} mm\n" +
            $"Rain         : {rain} mm\n" +
            $"Showers      : {showers} mm\n" +
            $"Snowfall     : {snowfall} cm\n" +
            $"Cloud cover  : {cloudCover} %\n" +
            $"Pressure MSL : {pressureMsl} hPa\n" +
            $"Surf. Press. : {surfacePressure} hPa\n" +
            $"Wind speed   : {windSpeed} km/h\n" +
            $"Wind dir.    : {windDirection} °\n" +
            $"Wind gusts   : {windGusts} km/h\n" +
            $"Is day       : {(isDay == 1 ? "Yes" : "No")}";
    }

    /// <summary>Human-readable label for WMO weather interpretation codes.</summary>
    private static string WmoDescription(int code)
    {
        switch (code)
        {
            case 0:  return "Clear sky";
            case 1:  return "Mainly clear";
            case 2:  return "Partly cloudy";
            case 3:  return "Overcast";
            case 45: return "Fog";
            case 48: return "Icy fog";
            case 51: return "Light drizzle";
            case 53: return "Moderate drizzle";
            case 55: return "Dense drizzle";
            case 61: return "Slight rain";
            case 63: return "Moderate rain";
            case 65: return "Heavy rain";
            case 71: return "Slight snow";
            case 73: return "Moderate snow";
            case 75: return "Heavy snow";
            case 77: return "Snow grains";
            case 80: return "Slight showers";
            case 81: return "Moderate showers";
            case 82: return "Violent showers";
            case 85: return "Slight snow showers";
            case 86: return "Heavy snow showers";
            case 95: return "Thunderstorm";
            case 96: return "Thunderstorm w/ slight hail";
            case 99: return "Thunderstorm w/ heavy hail";
            default: return "Unknown";
        }
    }

    // ?? TextMesh display ???????????????????????????????????????????????????
    private void SetupDisplayText()
    {
        GameObject textGO = new GameObject("WeatherDisplay");
        textGO.transform.SetParent(transform, false);
        // Position the panel slightly above and in front of the object
        textGO.transform.localPosition = new Vector3(0f, 0.25f, 0f);
        textGO.transform.localRotation = Quaternion.identity;
        textGO.transform.localScale    = Vector3.one * 0.004f;

        displayText = textGO.AddComponent<TextMesh>();
        displayText.fontSize  = 24;
        displayText.color     = Color.white;
        displayText.anchor    = TextAnchor.UpperLeft;
        displayText.alignment = TextAlignment.Left;
        displayText.text      = "Press trigger to\nfetch weather.";
    }

    private void UpdateDisplay(string message)
    {
        if (displayText != null)
            displayText.text = message;
    }

    // ?? Color helper ???????????????????????????????????????????????????????
    public void ChangeColor(Color color)
    {
        MeshRenderer meshRenderer = GetComponent<MeshRenderer>();
        if (meshRenderer != null)
            meshRenderer.material.color = color;
    }
}